# ---------------------------------------------------------------- 工具函数

def ctx():
    """生成一组替换用的占位符取值（同一条稿件内保持一致）。"""
    city = random.choice(CITIES)
    return {
        "city": city,
        "other": random.choice(OTHER_CITY),
        "n": random.choice(NUMS),
        "n2": random.choice(NUMS),
        "month": random.choice(MONTHS),
        "month2": random.choice(MONTHS),
        "name": random.choice(NAMES),
        # 机构名跟着 city 走，避免出现「江川市的稿件里写着云岭市城管局」这种自相矛盾
        "dept": city + random.choice(DEPT_SUFFIX),
        "issue": random.choice(ISSUES),
        "issue2": random.choice(ISSUES2),
        "thing": random.choice(THINGS),
        "unit": random.choice(UNITS),
        "industry": random.choice(INDUSTRIES),
        "hour": random.choice(HOURS),
    }


def build_article(topic_idx, k):
    """按题材与序号组装一条稿件的标题和正文段落。"""
    titles, leads, bodies = TOPICS[topic_idx]
    c = ctx()
    title = titles[k].format(**c)
    paras = [random.choice(leads).format(**c)]
    pool = bodies[:]
    random.shuffle(pool)
    for b in pool[: random.choice([2, 3])]:
        paras.append(b.format(**c))
    return title, paras


def make_dirty(lines, kinds):
    """按指定的「脏」类型加工文本行，制造第 2 课要清洗的问题。"""
    out = lines[:]
    if "dup_para" in kinds and len(out) > 2:
        i = random.randrange(1, len(out))
        out.insert(i, out[i])
    if "halfwidth" in kinds:
        out = [ln.replace("，", ",").replace("。", ".") if random.random() < 0.5 else ln
               for ln in out]
    if "trail_space" in kinds:
        out = [ln + " " if random.random() < 0.4 else ln for ln in out]
    if "lead_space" in kinds:
        out = ["  " + ln if random.random() < 0.3 else ln for ln in out]
    if "blank_lines" in kinds:
        for _ in range(random.randint(1, 3)):
            out.insert(random.randrange(0, len(out) + 1), "")
    text = "\n".join(out)
    if "pad_blank" in kinds:
        text = "\n\n   " + text + "\n\n"
    return text


DATE_STYLES = ["dash", "slash", "cn", "both"]


def date_line(style):
    """生成 2026-01-01 ~ 2026-09-16 之间的日期。

    上界卡在 9 月中旬：数据是 2026-09-17 造的，出现「未来」的发布时间会很别扭。
    """
    m = random.randint(1, 9)
    d = random.randint(1, 16) if m == 9 else random.randint(1, 28)
    hh, mm = random.randint(6, 22), random.choice([0, 15, 30, 45])
    if style == "dash":
        return f"2026-{m:02d}-{d:02d} {hh:02d}:{mm:02d}"
    if style == "slash":
        return f"2026/{m}/{d}"
    if style == "cn":
        return f"{m}月{d}日"
    return f"2026-{m:02d}-{d:02d}"


def write_text_lf(path, text):
    """统一用 LF 写文本。Windows 上默认会把 \\n 转成 CRLF，容易造成同一批文件换行不一致。"""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_csv(path, header, rows):
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


# ---------------------------------------------------------------- 1. 语料/ 60 篇稿件

def gen_corpus():
    plan = [(t, k) for t in range(6) for k in range(10)]  # 6 题材 × 10 = 60
    articles = []
    for topic_idx, k in plan:
        title, paras = build_article(topic_idx, k)
        articles.append((title, paras))

    kinds_pool = ["trail_space", "halfwidth", "dup_para", "blank_lines",
                  "lead_space", "pad_blank"]
    for i, (title, paras) in enumerate(articles, start=1):
        style = random.choice(DATE_STYLES)
        header = [f"标题：{title}"]
        if i % 8 != 0:  # 每 8 篇有 1 篇缺「来源」行
            header.append(f"来源：{random.choice(MEDIA)}")
        if style != "both":
            header.append(f"时间：{date_line(style)}")
        body = make_dirty(paras, random.sample(kinds_pool, random.randint(1, 3)))
        content = "\n".join(header) + "\n正文：\n" + body + "\n"
        write_text_lf(DIR_YULIAO / f"稿件_{i:03d}.txt", content)

    # 故意留 2 篇与前面**逐字节完全相同**的文件，供第 2 课练「去重」。
    # 必须整篇复制：如果各自随机加「脏数据」，两份就不再相同，去重练习就落空了。
    for dst, src in ((59, 12), (60, 33)):
        (DIR_YULIAO / f"稿件_{dst:03d}.txt").write_bytes(
            (DIR_YULIAO / f"稿件_{src:03d}.txt").read_bytes())

    # 清掉可能残留的旧文件（只清稿件_*.txt，不动别的东西）
    keep = {f"稿件_{i:03d}.txt" for i in range(1, 61)}
    for old in DIR_YULIAO.glob("稿件_*.txt"):
        if old.name not in keep:
            old.unlink()
    return 60


# ---------------------------------------------------------------- 2. data/ 300 条标题

def gen_titles():
    seen, rows = set(), []
    for t in range(6):
        got, tries = [], 0
        while len(got) < 48 and tries < 50000:  # 每题材 48 条，共 288
            tries += 1
            s = random.choice(TOPICS[t][0]).format(**ctx())
            if s not in seen:
                seen.add(s)
                got.append(s)
        for s in got:
            rows.append(s)
    for s in AMBIGUOUS_TITLES[:12]:  # 再加 12 条跨题材边界标题 → 300
        if s not in seen:
            seen.add(s)
            rows.append(s)
    random.shuffle(rows)  # 打散，避免同类扎堆

    out = []
    for i, title in enumerate(rows, start=1):
        out.append([i, title, random.choice(MEDIA), date_line("dash")])
    write_csv(DIR_DATA / "新闻标题_待标注.csv", ["编号", "标题", "来源", "发布时间"], out)
    return out


# ---------------------------------------------------------------- 3. data/ 200 条评论

def gen_comments(title_rows):
    rows, used = [], set()
    for label, count in COMMENT_PLAN.items():
        for text in COMMENT_POOLS[label][:count]:
            if text in used:
                raise SystemExit(f"评论池有重复文本：{text}")
            used.add(text)
            rows.append(text)
    assert len(rows) == 200, f"评论条数应为 200，实际 {len(rows)}"
    random.shuffle(rows)

    out = []
    for i, text in enumerate(rows, start=1):
        linked = random.randint(1, len(title_rows))
        out.append([i, linked, text, random.choice(PLATFORMS)])
    write_csv(DIR_DATA / "新闻评论_待分析.csv",
              ["编号", "关联标题编号", "评论内容", "平台"], out)
    return out


# ---------------------------------------------------------------- 4. 其余文件

def gen_stopwords():
    # 去重但保持原有顺序
    uniq = list(dict.fromkeys(STOPWORDS))
    write_text_lf(DIR_DATA / "停用词表_中文.txt", "\n".join(uniq) + "\n")
    return len(uniq)


def gen_annotation_sheet(title_rows):
    header = ["编号", "标题", "类别", "判定依据", "标注人", "是否边界情况", "备注"]
    rows = [[r[0], r[1], "", "", "", "", ""] for r in title_rows]
    write_csv(DIR_KEJIAN / "标注表_第3课.csv", header, rows)
    return len(rows)


